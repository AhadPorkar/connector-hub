#!/usr/bin/env python3
"""Capture existing, successful local reports; never fabricate a test result."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import json
import os
import platform
import shutil
import subprocess
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
out = root / 'docs/evidence'
(out/'reports').mkdir(parents=True, exist_ok=True)
suites=[]
for name in ('core','connectors','server','http','jdbc','browser'):
    path=root/'build/reports'/f'{name}.xml'
    doc=ET.parse(path).getroot()
    cases=list(doc.iter('testcase'))
    failed=sum(c.find('failure') is not None or c.find('error') is not None for c in cases)
    skipped=sum(c.find('skipped') is not None for c in cases)
    assert not failed, f'Report contains failures: {name}'
    assert cases, f'Empty report: {name}'
    suites.append({'name':name,'tests':len(cases),'passed':len(cases)-failed-skipped,'failures':failed,'skipped':skipped,'report':f'reports/{name}.xml','sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
    shutil.copy2(path,out/'reports'/path.name)
for path in (root/'build/screenshots').glob('*.png'):
    shutil.copy2(path,out/path.name)
java=subprocess.run(['java','-version'],capture_output=True,text=True,check=True)
evidence={
 'version':'0.1.0','status':'engineering-preview','recordedAtUtc':datetime.now(timezone.utc).isoformat(),
 'environment':{'platform':platform.platform(),'python':platform.python_version(),'java':(java.stderr or java.stdout).strip(),'browserTransport':'harness: real application assets; fetch bridge to actual Java server; native navigation and CSP not verified','jdbcAcceptance':'Environment-provided HSQLDB 1.8.0; driver not distributed or recommended'},
 'totalTests':sum(s['tests'] for s in suites),'totalPassed':sum(s['passed'] for s in suites),'suites':suites,
 'notVerified':['Native browser navigation and CSP enforcement','Live PostgreSQL, SQL Server, Oracle, MySQL, MariaDB, SQLite, H2, DB2, SAP HANA vendor acceptance','Live Redis and MongoDB acceptance','Full vendor stored-procedure and TLS behavior','Maven dependency resolution','Docker and Compose execution','Windows PowerShell launch and tests','Java 25 execution','Hosted GitHub Actions','Independent penetration test','Sustained load/soak and HA/failover','Legal/commercial certification'],
 'notes':['JUnit XML is generated by the repository test runners; no code-coverage percentage is claimed.','HTTP suites start the actual Java process and loopback fixtures.','Browser checks include UI actions and nine sections in all three languages.','Historical evidence is not automatically refreshed by normal test commands.','Regenerate only after successful actual execution of all required suites.']}
(out/'verification.json').write_text(json.dumps(evidence,indent=2)+'\n')
print(f"Captured {evidence['totalPassed']}/{evidence['totalTests']} passing tests.")
